-- USERS 테이블 조회 쿼리
-- 회원가입 후 데이터 저장 확인용

-- 전체 사용자 조회
SELECT 
    ID,
    USER_NAME,
    EMAIL,
    TEL,
    USER_TYPE,
    USER_STATUS,
    BUSINESS_NUMBER,
    CREATED_TIME
FROM USERS 
ORDER BY CREATED_TIME DESC;

-- 구매자만 조회
SELECT 
    ID,
    USER_NAME,
    EMAIL,
    TEL,
    USER_TYPE,
    CREATED_TIME
FROM USERS 
WHERE USER_TYPE = 'BUYER'
ORDER BY CREATED_TIME DESC;

-- 판매자만 조회
SELECT 
    ID,
    USER_NAME,
    EMAIL,
    TEL,
    USER_TYPE,
    BUSINESS_NUMBER,
    CREATED_TIME
FROM USERS 
WHERE USER_TYPE = 'SELLER'
ORDER BY CREATED_TIME DESC;

-- 최근 가입한 사용자 5명
SELECT 
    ID,
    USER_NAME,
    EMAIL,
    TEL,
    USER_TYPE,
    BUSINESS_NUMBER,
    CREATED_TIME
FROM USERS 
ORDER BY CREATED_TIME DESC
FETCH FIRST 5 ROWS ONLY;
